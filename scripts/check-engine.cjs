/**
 * Executes the inference path. Until this harness existed, nothing did.
 *
 * `engine.ts`, `gbm.ts` and `features.ts` type-checked, and `ml/test_train.py` covered the Python
 * side, but no test ever called `loadRiskEngine`, walked a tree in JavaScript, or turned a finding
 * into a rupee figure — because doing any of that needs a model artefact, and the real one is
 * blocked behind the data fetch. So the code that decides what a board sees had never run.
 *
 * This harness builds a model artefact by hand, in memory, and drives the real engine through all
 * three of its documented states: `trained`, `absent`, `rejected`. Three things make it more than a
 * smoke test.
 *
 * First, the arithmetic is cross-checked, not self-checked. `refPredict`/`refSigmoid`/`refInterp`
 * below are an independent implementation written from the serialisation format — a recursive walk
 * rather than the iterative one in `gbm.ts`, a guard-free sigmoid rather than the sign-branched one.
 * The parity fixture's expected values come from *those*, so `verifyParity()` passing means two
 * implementations agree, which is the same argument `ml/gbm.py:predict_from_dict` makes on the
 * Python side. A fixture generated by the code under test would prove nothing, and the harness
 * asserts it has teeth by perturbing an expected value and requiring the check to fail.
 *
 * Second, every rejection is exercised. A malformed artefact used to throw inside verification and
 * reject the whole `loadRiskEngine` promise, so a *corrupt* model looked exactly like a *missing*
 * one. Each mutation below asserts the load still resolves, the state is `rejected`, and the detail
 * names the actual fault.
 *
 * Third, nothing is written to `public/model/`. The artefact exists only as a string in this
 * process. An artefact on disk would be loaded by the running app, and a hand-built one carries no
 * information about anything — `data_is_real` is false and the generator string says so, but the
 * safest place for a fake model is nowhere.
 *
 * NOTHING HERE IS A MEASUREMENT. The trees are three hand-written splits. No number this harness
 * prints may be quoted as model performance; it validates arithmetic, plumbing and refusals.
 *
 * Run: node scripts/check-engine.cjs
 */
