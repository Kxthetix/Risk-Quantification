// --------------------------------------------------------------------------- //
// the parity fixture — expected values from the INDEPENDENT implementation
// --------------------------------------------------------------------------- //
/** Deterministic noise, so a failure is reproducible and a pass is not luck. */
function lcg(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

function buildRows(width, count, shape) {
  const rand = lcg(20260902);
  const rows = [];
  for (let i = 0; i < count; i += 1) {
    const row = new Array(width).fill(0);
    // Small non-zero noise everywhere: an all-zero row would pass even if the traversal read the
    // wrong column, because every wrong column would also be zero.
    for (let j = 0; j < width; j += 1) row[j] = Math.round(rand() * 1000) / 1000;
    shape(row, i);
    rows.push(row);
  }
  return rows;
}

// The shaping drives each fixture row to a specific leaf, so between them the rows visit every
// leaf in every tree. A parity fixture that only ever reached one leaf would agree trivially.
const EX_ROWS = buildRows(EXPLOIT_NAMES.length, 24, (row, i) => {
  row[0] = i % 2 === 0 ? 4.3 : 9.8;        // base_score, either side of 7
  row[6] = (i % 3) * 0.3;                   // epss, either side of 0.2
  row[10] = i % 4 < 2 ? 1 : 0;              // attackVector=NETWORK, either side of 0.5
});

const SV_ROWS = buildRows(SEVERITY_NAMES.length, 24, (row, i) => {
  row[1] = i % 2 === 0 ? 0.4 : 12.4;        // log_data_total, either side of 1
  row[2] = i % 3 === 0 ? 0 : 1;             // n_data_varieties, either side of 0.5
});

function goodFixture() {
  const raw = EX_ROWS.map((r) => refPredict(EXPLOIT_GBM, r));
  const prob = raw.map(refSigmoid);
  // Cloned for the same reason goodModel() is: callers mutate the result to build the malformed
  // cases, and EX_ROWS / EXPLOIT_NAMES are shared module-level constants.
  return clone({
    note:
      `${FIXTURE_NOTE} Expected values are computed by refPredict/refSigmoid/refInterp in the ` +
      'harness, which is a second implementation of the format — so agreement is a cross-check of ' +
      'src/model/gbm.ts, not a restatement of it.',
    exploitation: {
      feature_names: EXPLOIT_NAMES,
      rows: EX_ROWS,
      expected_raw: raw,
      expected_probability: prob,
      expected_calibrated: prob.map((p) => refInterp(CALIBRATION, p)),
    },
    severity: {
      feature_names: SEVERITY_NAMES,
      rows: SV_ROWS,
      expected_log10_mean: SV_ROWS.map((r) => refPredict(SEVERITY_MEAN_GBM, r)),
      expected_log10_p10: SV_ROWS.map((r) => refPredict(SEVERITY_P10_GBM, r)),
      expected_log10_p90: SV_ROWS.map((r) => refPredict(SEVERITY_P90_GBM, r)),
    },
  });
}

/** Deep clone through JSON: the artefact is JSON by definition, so nothing is lost. */
function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

async function load({ model, fixture, crosswalk = CROSSWALK, extra = {}, headers, bodyThrows }) {
  const routes = { [CROSSWALK_URL]: { body: crosswalk }, ...extra };
  // `headers` and `bodyThrows` attach to the artefact routes only: they exist to model a host that
  // mislabels a content type and a transfer that dies mid-body, both of which are about the model.
  const trim = (route) => ({ ...route, ...(headers ? { headers } : {}), ...(bodyThrows ? { bodyThrows } : {}) });
  if (model !== undefined) {
    routes[MODEL_URL] = trim(typeof model === 'string' ? { body: model } : { body: JSON.stringify(model) });
  }
  if (fixture !== undefined) {
    routes[FIXTURE_URL] = trim(typeof fixture === 'string' ? { body: fixture } : { body: JSON.stringify(fixture) });
  }
  installFetch(routes);
  return loadRiskEngine({ modelUrl: MODEL_URL, fixtureUrl: FIXTURE_URL, crosswalkUrl: CROSSWALK_URL });
}

