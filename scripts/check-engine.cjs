/**
 * `loadRiskEngine` and `loadCrosswalk` both call global `fetch`. Stubbing that rather than
 * refactoring them for injection means the harness drives exactly the code the browser runs,
 * including the status/ok handling that decides `absent` from `rejected`.
 */
function installFetch(routes) {
  // Modelled on a real `Response`, headers included. The loader reads `content-type` to corroborate
  // an HTML body, and a stub without headers would crash the very function whose job is to report a
  // fault calmly — the stub has to offer the interface the shipped code is allowed to assume.
  const headers = (map) => ({
    get: (name) => {
      const key = String(name).toLowerCase();
      const hit = Object.keys(map || {}).find((k) => k.toLowerCase() === key);
      return hit === undefined ? null : map[hit];
    },
  });
  global.fetch = async (url) => {
    const route = routes[String(url)];
    if (route === undefined) {
      return {
        ok: false,
        status: 404,
        headers: headers({}),
        text: async () => 'Not Found',
        json: async () => {
          throw new Error('no body');
        },
      };
    }
    if (route.throws) throw new Error(route.throws);
    const status = route.status ?? 200;
    return {
      ok: status >= 200 && status < 300,
      status,
      headers: headers(route.headers ?? { 'content-type': 'application/json' }),
      json: async () => JSON.parse(route.body),
      text: async () => {
        if (route.bodyThrows) throw new Error(route.bodyThrows);
        return route.body;
      },
    };
  };
}

// --------------------------------------------------------------------------- //
// an independent implementation of the exported format
// --------------------------------------------------------------------------- //
/**
 * Written from the serialisation contract, not from `gbm.ts`. Recursive where the shipped code is
 * iterative; no overflow guard on the sigmoid; a linear scan where the shipped calibrator binary
 * searches. The point of the differences is that a shared mistake is less likely.
 */
function refPredict(model, row) {
  let out = model.base_score;
  for (const tree of model.trees) {
    const walk = (node) => {
      if (tree.feature[node] < 0) return tree.value[node];
      const goLeft = row[tree.feature[node]] <= tree.threshold[node];
      return walk(goLeft ? tree.left[node] : tree.right[node]);
    };
    out += model.learning_rate * walk(0);
  }
  return out;
}

function refSigmoid(z) {
  return 1 / (1 + Math.exp(-z));
}

/** numpy.interp, spelled out: clamp outside the knots, linear between them. */
function refInterp(cal, p) {
  const { x, y } = cal;
  if (p <= x[0]) return y[0];
  if (p >= x[x.length - 1]) return y[y.length - 1];
  for (let i = 1; i < x.length; i += 1) {
    if (p <= x[i]) {
      const span = x[i] - x[i - 1];
      if (span === 0) return y[i - 1];
      return y[i - 1] + ((p - x[i - 1]) * (y[i] - y[i - 1])) / span;
    }
  }
  return y[y.length - 1];
}

function maxDelta(a, b) {
  let worst = 0;
  for (let i = 0; i < a.length; i += 1) {
    const d = Math.abs(a[i] - b[i]);
    if (d > worst) worst = d;
  }
  return worst;
}

// --------------------------------------------------------------------------- //
// the fixture artefact — three hand-written splits, in memory, labelled as such
// --------------------------------------------------------------------------- //
/** Leaf padding, spelled the way ml/gbm.py:to_dict spells it: threshold 0.0, unread children. */
function leaf(value) {
  return { feature: -1, threshold: 0, left: 0, right: 0, value };
}

function split(featureIndex, threshold, left, right) {
  return { feature: featureIndex, threshold, left, right, value: 0 };
}

/** Assemble the columnar tree format from a node list, so the fixtures stay readable. */
function tree(nodes) {
  return {
    feature: nodes.map((n) => n.feature),
    threshold: nodes.map((n) => n.threshold),
    left: nodes.map((n) => n.left),
    right: nodes.map((n) => n.right),
    value: nodes.map((n) => n.value),
  };
}

